"""Print the JavaScript data block that the gh-pages index.html embeds for
the P/E chart and the calculator's out-of-sample band.

Inputs (main branch):
  data/raw/valuation/ndx_pe_trailing.csv                 trailing P/E points
  data/raw/valuation/ndx_annual_pe_nasdaq_approx_2001_2022.csv
  data/raw/valuation/ndx_forward_weekly_2001_2026.csv    History of Market
  data/processed/ndx_daily.csv                           to place annual points
  data/processed/oos_trend_errors.csv                    from oos_trend_test.py

Days are counted from 1985-10-01, the page's T0. Usage:
  python scripts/page_embed.py > /tmp/embed.js
"""
import csv
import datetime as dt
import json
import os

import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VAL = os.path.join(ROOT, "data", "raw", "valuation")
T0 = dt.date(1985, 10, 1)


def day(s):
    return (dt.date.fromisoformat(s) - T0).days


def rows(name):
    with open(os.path.join(VAL, name), encoding="utf-8-sig") as f:
        return list(csv.DictReader(f))


def num(x):
    v = float(x)
    return int(v) if v == int(v) else round(v, 2)


def main():
    ttm = [[day(r["date"]), num(r["pe"]), 1 if r["source"] == "siblis" else 0] for r in rows("ndx_pe_trailing.csv")]

    # annual FY P/E: the source gives years only; plot each at that year's last trading day
    daily = pd.read_csv(os.path.join(ROOT, "data", "processed", "ndx_daily.csv"), parse_dates=["date"])
    year_end = daily.groupby(daily["date"].dt.year)["date"].max()
    fy = [[day(year_end[int(r["year"])].date().isoformat()), num(r["pe"]), int(r["year"])]
          for r in rows("ndx_annual_pe_nasdaq_approx_2001_2022.csv")]

    fwd = [[day(r["date"]), num(r["value"])] for r in rows("ndx_forward_weekly_2001_2026.csv")]

    o = pd.read_csv(os.path.join(ROOT, "data", "processed", "oos_trend_errors.csv"))
    band = o[(o.rule == "close") & (o.window == "4y")].sort_values("horizon_months")
    # raw percentiles, so the calculator's 12-month range matches the table exactly
    lo = band.err_p10.to_numpy()
    hi = band.err_p90.to_numpy()
    tab = []
    for rule, win in (("close", "3y"), ("close", "4y"), ("close", "5y"), ("close", "10y"), ("close", "all"), ("trend", "4y")):
        r = o[(o.rule == rule) & (o.window == win) & (o.horizon_months == 12)].iloc[0]
        tab.append([rule, win, round(r.err_p10, 4), round(r.err_p50, 4), round(r.err_p90, 4),
                    round(r.share_within_insample_1sigma, 3), int(r.n)])
    oos = {"h": band.horizon_months.astype(int).tolist(), "lo": [round(x, 4) for x in lo],
           "hi": [round(x, 4) for x in hi], "tab": tab}

    out = []
    out.append("// P/E series and out-of-sample errors, generated by scripts/page_embed.py on the main branch")
    out.append("// trailing P/E: [day, P/E, source] with source 1 = Siblis Research, 0 = Nasdaq index research")
    out.append("var PE_TTM = " + json.dumps(ttm, separators=(",", ":")) + ";")
    out.append("// Nasdaq's annual FY P/E, read off the chart on p.18 of its December 2022 presentation (2001 is the printed 208.3): [day of that year's last close, P/E, year]")
    out.append("var PE_FY = " + json.dumps(fy, separators=(",", ":")) + ";")
    out.append("// 12-month forward P/E, weekly, History of Market (CC BY 4.0): [day, P/E]")
    out.append("var PE_FWD = " + json.dumps(fwd, separators=(",", ":")) + ";")
    out.append("// rolling out-of-sample errors, ln(actual / forecast): band = 4-year slope from the latest close, 10th/90th percentile by months ahead; tab = 12-month rows [rule, window, p10, p50, p90, share inside in-sample ±1σ, n]")
    out.append("var OOS = " + json.dumps(oos, separators=(",", ":")) + ";")
    print("\n".join(out))


if __name__ == "__main__":
    main()
